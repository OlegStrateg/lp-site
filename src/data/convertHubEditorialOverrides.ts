export function applyConvertHubEditorialOverrides(locales: ConvertHubLocale[]): void {
  for (const locale of locales) {
    const patch = CORE_COPY_PATCHES[locale.code];
    if (!patch) continue;
    Object.assign(locale.copy, patch);
  }
}
